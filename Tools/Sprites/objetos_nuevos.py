def rejilla(texto, colores, n):
    filas = [f for f in texto.strip("\n").split("\n")]
    filas = (filas + ["." * n] * n)[:n]
    col = dict(colores)
    col["#"] = CONTORNO
    out = []
    for f in filas:
        f = f.replace(" ", ".")[:n].ljust(n, ".")
        out.append([None if ch == "." else col[ch] for ch in f])
    return out


def contornear(img):
    """1 px de contorno alrededor de todo lo pintado (como los sprites del pack)."""
    n = len(img)
    nuevo = [fila[:] for fila in img]
    for y in range(n):
        for x in range(n):
            if img[y][x] is not None:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if 0 <= xx < n and 0 <= yy < n and img[yy][xx] is not None and img[yy][xx][3] > 200:
                    nuevo[y][x] = CONTORNO
                    break
    return nuevo


def icono(texto, colores):
    return contornear(rejilla(texto, colores, 32))


