def puesto16(texto, col, f=0):
    filas = texto.strip("\n").split("\n")
    filas = [r.ljust(16, ".")[:16] for r in filas] + [V16] * (16 - len(filas))
    return P.capa("Equipo", "\n".join(filas), col, f)


