def parsear(texto, leyenda, f=0):
    """Texto de 16 filas -> filas de colores RGBA (None = transparente)."""
    filas = texto.strip("\n").split("\n")
    assert len(filas) == T, len(filas)
    colores = dict(COMUNES)
    colores.update(leyenda)
    if PARPADEO[f]:
        colores["e"] = colores.get("K", colores["#"])
        colores["g"] = colores["#"]          # ojos que brillan (dentro de un visor): se apagan
    px = []
    for fila in filas:
        assert len(fila) == T, repr(fila)
        px.append([None if ch == "." else colores[ch] for ch in fila])
    return px


def mover(px, dx, dy):
    nuevo = [[None] * T for _ in range(T)]
    for y in range(T):
        for x in range(T):
            if px[y][x] is not None and 0 <= x + dx < T and 0 <= y + dy < T:
                nuevo[y + dy][x + dx] = px[y][x]
    return nuevo


def capa(nombre, texto, leyenda, f):
    px = parsear(texto, leyenda, f)
    if nombre not in FIJAS:
        px = mover(px, *DESPLAZ_ARRIBA[f])
    return px


def exportar(ruta, capas):
    """capas: [(nombre, texto, leyenda)] de atrás adelante -> .ase con 4 fotogramas de reposo."""
    from ase import Sprite
    s = Sprite(T, T)
    for nombre, _, _ in capas:
        s.capa(nombre)
    for f in range(FOTOGRAMAS):
        s.fotograma(DURACION_MS)
    for i, (nombre, texto, leyenda) in enumerate(capas):
        for f in range(FOTOGRAMAS):
            s.pintar(i, f, capa(nombre, texto, leyenda, f))
    s.etiqueta("reposo", 0, FOTOGRAMAS - 1)
    s.guardar(ruta)
    print("escrito", ruta)


def guardar_plantilla(carpeta):
    datos = {
        "tamano": T, "fotogramas": FOTOGRAMAS, "duracion_ms": DURACION_MS,
        "desplazamiento_arriba": DESPLAZ_ARRIBA, "capas_fijas": sorted(FIJAS),
        "anclas": ANCLAS, "orden_capas": ORDEN_CAPAS,
        "contorno": "#2a1d26, 1 px dibujado en cada pieza; nunca debajo de los pies",
        "nota": "Una prenda u objeto se dibuja a 16x16 en la posición del fotograma 0; las capas no fijas bajan con desplazamiento_arriba.",
    }
    with open(os.path.join(carpeta, "plantilla.json"), "w", encoding="utf-8") as fh:
        json.dump(datos, fh, ensure_ascii=False, indent=2)
