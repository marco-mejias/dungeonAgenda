# Plantilla común de los héroes a 16x16 ("píxel gordo", como los sprites antiguos), pensada para
# ponerles ropa y objetos fácilmente:
#   - Los CUATRO héroes comparten silueta y puntos de enganche (manos, cabeza, torso...), así una
#     prenda u objeto dibujado una vez vale para todos.
#   - Cada capa se dibuja a mano como texto: un carácter = un píxel, con su leyenda de colores.
#     El contorno ('#') va dibujado en cada pieza, de 1 px, igual de gordo que cualquier detalle.
#   - Debajo de los pies no hay contorno: apoyan directamente en la sombra.
#   - Reposo de 4 fotogramas: la parte de arriba (todo menos sombra y piernas) baja 1 px en los
#     fotogramas 2 y 3. En el 3 parpadea: los ojos ('e') se cierran.

